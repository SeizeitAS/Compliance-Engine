// Generates golden test vectors from the TypeScript reference implementation.
// The compiled circuit must reproduce every value (scripts/crosscheck-circuit.mjs).
// Usage: node scripts/gen-vectors.ts > test/vectors/nonmembership-vectors.json
import { SanctionsTree, deriveKey, hashLeaf, hashNode, pathDirections, KEY_SPACE } from "../src/sanctions/indexedMerkleTree.ts";

const DEPTH = 20; // must equal the circuit's tree depth
const listed = ["NO:fnr:11111111111", "NO:fnr:22222222222", "NO:fnr:33333333333"].map((s) => deriveKey(s));
const tree = new SanctionsTree(listed, DEPTH);
const probe = deriveKey("NO:fnr:44444444444");
const p = tree.prove(probe)!;
const hex = (n: bigint) => n.toString();

const leaf = hashLeaf(p.lo, p.hi);
console.log(
  JSON.stringify(
    {
      note: "Generated by scripts/gen-vectors.ts. Numbers are decimal strings, hashes are lowercase hex.",
      depth: DEPTH,
      keySpace: hex(KEY_SPACE),
      hashLeaf: [
        { lo: "0", hi: hex(KEY_SPACE), out: hashLeaf(0n, KEY_SPACE) },
        { lo: hex(p.lo), hi: hex(p.hi), out: leaf },
      ],
      hashNode: [{ left: leaf, right: p.siblings[0], out: hashNode(leaf, p.siblings[0]) }],
      tree: { listedKeys: listed.map(hex), root: tree.root },
      nonMember: {
        key: hex(probe),
        lo: hex(p.lo),
        hi: hex(p.hi),
        index: p.index,
        siblings: p.siblings,
        isRight: pathDirections(p.index, DEPTH),
        leaf,
        root: tree.root,
      },
    },
    null,
    2,
  ),
);
